// Purpose: Dataset keys, observation schema and layout own all derived access contracts.

import { Schema, SchemaAST } from "effect";
import {
  defineDataFrame,
  type DataFrame,
  type DataFrameKind,
  type DataFrameSpec,
  type FieldSchema,
} from "@openchart/timeseries";
import { fatal } from "@openchart/utils/assert";
import type { KeySchema } from "./key";
import { register } from "./registry";

/** The result layout shared by every operation on a Dataset. */
export enum Layout {
  Row = "row",
  Timeseries = "timeseries",
}
/** Supported Dataset access modes; Dataset errors name the failed mode. */
export const Mode = Schema.Literals(["select", "search", "stream"]);
/** One supported Dataset access mode. */
export type Mode = typeof Mode.Type;
/** At least one operation must be enabled; omitted modes are unavailable. */
export type Access = Readonly<
  | { select: true; stream?: true; search?: true }
  | { select?: true; stream: true; search?: true }
  | { select?: true; stream?: true; search: true }
>;
/** Independent address fields, each explicitly marked with k.eq or k.range. */
export type Keys = Schema.Struct<Readonly<Record<string, KeySchema>>>;
/** One observation's native Effect schema, independent of its address. */
export type ObservationSchema = Schema.Struct<
  Readonly<Record<string, Schema.Codec<unknown, unknown>>>
>;
/** A derived operation codec; callers never author a parallel input/output pair. */
export interface DatasetOperation {
  readonly input: Schema.Codec<unknown, unknown>;
  readonly output: Schema.Codec<unknown, unknown>;
}
/** Erased view of the non-empty operations generated by defineDataset. */
export type DatasetAccess = Partial<Readonly<Record<Mode, DatasetOperation>>> &
  (
    | { readonly select: DatasetOperation }
    | { readonly stream: DatasetOperation }
    | { readonly search: DatasetOperation }
  );
/** Pure Dataset description; credentials and acquisition belong to Providers. */
export interface DatasetDefinition {
  readonly name: string;
  readonly keys: Keys;
  readonly schema: ObservationSchema;
  readonly layout: Layout;
  readonly access: DatasetAccess;
}

const Count = Schema.optionalKey(Schema.Int.check(Schema.isGreaterThan(0)));
const Score = Schema.optionalKey(Schema.Finite);
/** Shared text-search query, independent of a Dataset's structural keys. */
export const SearchQuery = Schema.Struct({
  query: Schema.String,
  limit: Count,
}).annotate({ parseOptions: { onExcessProperty: "error" } });
export type SearchQuery = typeof SearchQuery.Type;

type Range<S extends Schema.Codec<unknown, unknown>> = Schema.Struct<{
  from: Schema.optionalKey<S>;
  to: Schema.optionalKey<S>;
}>;
type Selector<S extends KeySchema> = S["keyKind"] extends "eq"
  ? S
  : S["~type.optionality"] extends "optional"
    ? Schema.optionalKey<Range<S>>
    : Range<S>;
type SelectFields<K extends Keys> = {
  [P in keyof K["fields"]]: Selector<K["fields"][P]>;
} & { count: typeof Count };
type StreamFields<K extends Keys> = {
  [
    P in keyof K["fields"] as K["fields"][P]["keyKind"] extends "eq" ? P : never
  ]: K["fields"][P];
};
type FrameSpec<S extends ObservationSchema> = {
  [P in Exclude<keyof S["fields"], "time">]: Extract<
    S["fields"][P],
    FieldSchema
  >;
};
type Output<
  S extends ObservationSchema,
  L extends Layout,
  M extends Mode,
> = L extends Layout.Timeseries
  ? Schema.Codec<DataFrame<FrameSpec<S>>, string>
  : M extends "stream"
    ? S
    : M extends "search"
      ? Schema.$Array<Schema.Struct<S["fields"] & { score: typeof Score }>>
      : Schema.$Array<S>;
/** A Dataset's exact access codecs, generated from its keys, schema and layout. */
export type Definition<
  N extends string,
  K extends Keys,
  S extends ObservationSchema,
  L extends Layout,
  A extends Access,
> = {
  readonly name: N;
  readonly keys: K;
  readonly schema: S;
  readonly layout: L;
  /** The declaration-derived frame constructor; row layouts have no frame. */
  readonly frame: L extends Layout.Timeseries
    ? DataFrameKind<FrameSpec<S>>
    : undefined;
  readonly access: {
    readonly [M in keyof A & Mode]: {
      readonly input: M extends "select"
        ? Schema.Struct<SelectFields<K>>
        : M extends "stream"
          ? Schema.Struct<StreamFields<K>>
          : typeof SearchQuery;
      readonly output: Output<S, L, M>;
    };
  };
};
/** Input accepted by one declared operation. */
export type DatasetInput<D extends DatasetDefinition, M extends Mode> =
  NonNullable<D["access"][M]> extends DatasetOperation
    ? NonNullable<D["access"][M]>["input"]["Type"]
    : never;
/** Decoded output produced by one declared operation. */
export type DatasetOutput<D extends DatasetDefinition, M extends Mode> =
  NonNullable<D["access"][M]> extends DatasetOperation
    ? NonNullable<D["access"][M]>["output"]["Type"]
    : never;
/** Finite query derived from equality/range keys plus count. */
export type SelectQuery<D extends DatasetDefinition> = DatasetInput<
  D,
  "select"
>;
/** Rows or the canonical timeseries DataFrame, according to layout. */
export type SelectResult<D extends DatasetDefinition> = DatasetOutput<
  D,
  "select"
>;
/** Live query derived from equality keys only. */
export type StreamQuery<D extends DatasetDefinition> = DatasetInput<
  D,
  "stream"
>;
/** One row or one canonical DataFrame per emission, according to layout. */
export type StreamResult<D extends DatasetDefinition> = DatasetOutput<
  D,
  "stream"
>;
/** Observation type from the Dataset schema, including stream-only Datasets. */
export type RowOf<D extends DatasetDefinition> = D["schema"]["Type"];
/** DataFrame columns derived from the observation schema, excluding time. */
export type DataFrameSpecOf<D extends DatasetDefinition> =
  D["layout"] extends Layout.Timeseries ? FrameSpec<D["schema"]> : never;
/** One search observation with an optional provider score. */
export type SearchResult<D extends DatasetDefinition> =
  DatasetOutput<D, "search"> extends readonly (infer Row)[] ? Row : never;

type RequiredNumber = Schema.Codec<number, number> & {
  "~type.optionality": "required";
};
type SeriesSchema<S extends ObservationSchema> = S["fields"] extends {
  time: RequiredNumber;
}
  ? Exclude<
      S["fields"][keyof S["fields"]],
      FieldSchema & { "~type.optionality": "required" }
    > extends never
    ? S
    : never
  : never;
type RangeNames<K extends Keys> = {
  [P in keyof K["fields"]]: K["fields"][P]["keyKind"] extends "range"
    ? P
    : never;
}[keyof K["fields"]];
type SeriesKeys<K extends Keys> = K["fields"] extends {
  time: KeySchema<RequiredNumber, "range">;
}
  ? Exclude<RangeNames<K>, "time"> extends never
    ? K
    : never
  : never;
type ExactAccess<A> = Record<Exclude<keyof A, Mode>, never>;
type SeriesAccess = Readonly<
  | { select: true; stream?: true; search?: never }
  | { select?: true; stream: true; search?: never }
>;

/**
 * Declares and registers a Dataset from its independent address and observations.
 * Row layout selects/searches arrays and streams rows. Timeseries layout derives
 * one native DataFrame codec for both select and stream from the response schema.
 * Queries, results and Provider methods all derive from this declaration.
 * @throws If its name, keys, layout or access modes violate the Dataset contract.
 * @example
 * const prices = defineDataset({
 *   name: 'prices',
 *   keys: Schema.Struct({symbol: k.eq(Schema.String), time: k.range(Schema.Int)}),
 *   schema: Schema.Struct({time: Schema.Int, close: Schema.Finite}),
 *   layout: Layout.Timeseries,
 *   access: {select: true, stream: true},
 * });
 */
export function defineDataset<
  const N extends string,
  K extends Keys,
  S extends ObservationSchema,
  const A extends Access,
>(definition: {
  name: N & (string extends N ? never : unknown);
  keys: K;
  schema: S;
  layout: Layout.Row;
  access: A & ExactAccess<A>;
}): Definition<N, K, S, Layout.Row, A>;
export function defineDataset<
  const N extends string,
  K extends Keys,
  S extends ObservationSchema,
  const A extends SeriesAccess,
>(definition: {
  name: N & (string extends N ? never : unknown);
  keys: SeriesKeys<K>;
  schema: SeriesSchema<S>;
  layout: Layout.Timeseries;
  access: A & ExactAccess<A>;
}): Definition<N, K, S, Layout.Timeseries, A>;
export function defineDataset(definition: RuntimeDeclaration): unknown {
  return defineRuntimeDataset(definition);
}

/** A declaration whose name and observation schema exist only at runtime. */
export interface RuntimeDeclaration {
  readonly name: string;
  readonly keys: Keys;
  readonly schema: ObservationSchema;
  readonly layout: Layout;
  readonly access: Access;
}

/** An erased declaration with its derived frame constructor, if timeseries. */
export type RuntimeDefinition = DatasetDefinition & {
  readonly frame: DataFrameKind<DataFrameSpec> | undefined;
};

/**
 * Declares and registers a Dataset described by user data, such as a Resource,
 * applying every {@link defineDataset} check. The Provider that publishes it
 * owns its name: it calls `unregister` after retiring the last instance.
 * @throws If its name is taken or its keys, layout or access modes violate the Dataset contract.
 * @example
 * const definition = defineRuntimeDataset({
 *   name: `workspace.${id}`,
 *   keys: Schema.Struct({time: k.range(Schema.Number)}),
 *   schema: Schema.Struct({time: Schema.Number, close: Schema.Finite}),
 *   layout: Layout.Timeseries,
 *   access: {select: true},
 * });
 */
export function defineRuntimeDataset(
  definition: RuntimeDeclaration,
): RuntimeDefinition {
  const { name, keys, layout } = definition;
  const modes = Object.entries(definition.access);
  if (
    !name ||
    modes.length === 0 ||
    modes.some(
      ([mode, enabled]) =>
        !["select", "search", "stream"].includes(mode) || enabled !== true,
    )
  )
    fatal(
      "Dataset requires a name and at least one enabled select/search/stream mode",
    );
  if (
    !Schema.isSchema(keys) ||
    !Schema.isSchema(definition.schema) ||
    keys.ast._tag !== "Objects" ||
    definition.schema.ast._tag !== "Objects"
  )
    fatal("Dataset keys and observation schema must be Struct schemas");
  if (layout !== Layout.Row && layout !== Layout.Timeseries)
    fatal("Unknown Dataset layout");
  const select: Record<string, Schema.Codec<unknown, unknown>> = {};
  const stream: Record<string, Schema.Codec<unknown, unknown>> = {};
  const ranges: string[] = [];
  for (const [field, key] of Object.entries(keys.fields)) {
    if (field === "count" || field === "limit")
      fatal(`Dataset key name "${field}" is reserved`);
    if (key.keyKind === "eq") {
      select[field] = stream[field] = key;
    } else if (key.keyKind === "range") {
      ranges.push(field);
      const range = Schema.Struct({
        from: Schema.optionalKey(key),
        to: Schema.optionalKey(key),
      }).annotate({ parseOptions: { onExcessProperty: "error" } });
      select[field] = SchemaAST.isOptional(key.ast)
        ? Schema.optionalKey(range)
        : range;
    } else fatal(`Dataset key "${field}" must be marked with k.eq or k.range`);
  }
  const schema = definition.schema.annotate({
    parseOptions: { onExcessProperty: "error" },
  });
  let output: Schema.Codec<unknown, unknown> = Schema.Array(schema);
  let frame: DataFrameKind<DataFrameSpec> | undefined;
  if (layout === Layout.Timeseries) {
    const { time, ...fields } = schema.fields;
    const timeKey = keys.fields.time;
    if (!time || time.ast._tag !== "Number" || SchemaAST.isOptional(time.ast))
      fatal("Timeseries Dataset schema requires a numeric time field");
    if (
      ranges.length !== 1 ||
      ranges[0] !== "time" ||
      !timeKey ||
      timeKey.ast._tag !== "Number" ||
      SchemaAST.isOptional(timeKey.ast)
    )
      fatal("Timeseries Dataset keys require one numeric range key named time");
    if (definition.access.search)
      fatal("Timeseries Dataset does not support search");
    for (const field of Object.values(fields)) {
      if (SchemaAST.isOptional(field.ast))
        fatal("Timeseries columns cannot be optional");
    }
    // @agent invariant: timeseries owns DataFrame validation and wire encoding;
    // Dataset derives its spec once and uses the same codec for select and stream.
    const derived = defineDataFrame(
      fields as DataFrameSpec,
      time as RequiredNumber,
    );
    frame = derived;
    output = derived.codec;
  }
  const access: Partial<Record<Mode, DatasetOperation>> = {};
  if (definition.access.select)
    access.select = {
      input: Schema.Struct({ ...select, count: Count }).annotate({
        parseOptions: { onExcessProperty: "error" },
      }),
      output,
    };
  if (definition.access.stream)
    access.stream = {
      input: Schema.Struct(stream).annotate({
        parseOptions: { onExcessProperty: "error" },
      }),
      output: layout === Layout.Timeseries ? output : schema,
    };
  if (definition.access.search) {
    if ("score" in schema.fields)
      fatal("Searchable Dataset reserves the score field");
    // Adding only score preserves every check on the unchanged observation fields.
    const searchRow = schema
      .mapFields((fields) => ({ ...fields, score: Score }), {
        unsafePreserveChecks: true,
      })
      .annotate({ parseOptions: { onExcessProperty: "error" } });
    access.search = { input: SearchQuery, output: Schema.Array(searchRow) };
  }
  // Every enabled mode was checked above and generated here, so access is non-empty.
  const result = {
    name,
    keys,
    schema,
    layout,
    frame,
    access: access as DatasetAccess,
  };
  register(result);
  return result;
}
